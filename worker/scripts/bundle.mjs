import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { plainJavaScript } from './transpile.mjs';
import { catalog as sourceCatalog } from '../../src/data/catalog.ts';
const output = fileURLToPath(new URL('../dist/worker.js', import.meta.url));
const contractSource = await readFile(new URL('../../src/data/catalog-contract.ts', import.meta.url), 'utf8');
const contextSource = await readFile(new URL('../../src/data/interest-context.ts', import.meta.url), 'utf8');
const workerSource = await readFile(new URL('../src/index.ts', import.meta.url), 'utf8');
const contractScript = plainJavaScript(contractSource, ['./catalog.ts']);
const contextScript = plainJavaScript(contextSource);
const workerScript = plainJavaScript(workerSource, ['./catalog.ts', '../../src/data/catalog-contract.ts', '../../src/data/interest-context.ts'], false);
const priceCatalog = sourceCatalog.map(({ id, variants }) => ({ id, variants: variants.map(({ value, price }) => ({ value, price })) }));
const bundled = `// Generated locally. No credentials.\nconst sourceCatalog = ${JSON.stringify(priceCatalog)};\nconst catalog = Object.fromEntries(sourceCatalog.map(product => [product.id, Object.fromEntries(product.variants.map(variant => [String(variant.value), variant.price]))]));\n${contractScript}\n${contextScript}\n${workerScript}`;
await mkdir(new URL('../dist/', import.meta.url), { recursive: true });
await writeFile(output, bundled);
process.stdout.write(`${output}\n`);
