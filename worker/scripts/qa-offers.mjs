import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { bundles } from '../../src/data/bundles.ts';
import { catalog } from '../../src/data/catalog.ts';
import { selectionPrice } from '../../src/lib/selection-offers.ts';

export async function verifyOffers(page, origin, width, screenshotDir) {
  await mkdir(screenshotDir, { recursive: true });
  let visit = 0;
  const selection = () => page.evaluate(() => JSON.parse(localStorage.getItem('pirogorsk-selection') || '[]'));
  const clear = () => page.evaluate(() => localStorage.removeItem('pirogorsk-selection'));
  for (const bundle of bundles) {
    await clear();
    await page.goto(`${origin}/?qa=1&offer-check=${visit++}#nabory`, { waitUntil: 'networkidle0' });
    assert.equal(await page.$$eval('.offer-card', cards => cards.length), 3);
    assert.equal(await page.$$eval('.offer-art [data-supplier-artwork]', images => images.length), 2);
    await page.click(`[data-bundle="${bundle.id}"]`);
    assert.equal(await page.$eval('#selection-dialog', dialog => dialog.open), true);
    assert.deepEqual(await selection(), bundle.items);
    assert.equal(await page.$eval('[data-total]', el => Number(el.textContent.replace(/\D/g, ''))), selectionPrice(bundle.items, catalog));
    assert.equal(await page.$eval('[data-selection-grand-total]', el => Number(el.textContent.replace(/\D/g, ''))), selectionPrice(bundle.items, catalog) + 500);
    assert.equal(await page.$eval('[data-upsell-group=sweet]', el => el.hidden), bundle.id === 'sweet-table');
    assert.equal(await page.evaluate(() => document.body.scrollWidth <= innerWidth), true);
    assert.equal(await page.$eval('#selection-dialog', el => el.scrollWidth <= el.clientWidth), true);
  }
  await clear();
  await page.goto(`${origin}/?qa=1&offer-check=${visit++}#nabory`, { waitUntil: 'networkidle0' });
  await page.$eval('#nabory', el => el.scrollIntoView());
  await page.screenshot({ path: `${screenshotDir}/bundles-${width}.png`, fullPage: false });
  await page.click('[data-bundle=dinner]');
  await page.select('[data-upsell-choice=morse]', 'seabuckthorn:1000:1');
  assert.match(await page.$eval('[data-upsell-add=morse]', el => el.textContent), /350/);
  await page.$eval('[data-upsells]', el => el.scrollIntoView());
  await page.screenshot({ path: `${screenshotDir}/addons-${width}.png` });
  assert.equal(await page.$$eval('.addon-add', buttons => buttons.every(button => button.getBoundingClientRect().height >= 44)), true);
  await page.click('[data-upsell-add=morse]');
  assert.equal(await page.$eval('[data-upsell-group=morse]', el => el.hidden), true);
  await page.select('[data-upsell-choice=sweet]', 'cherry:500:1');
  await page.click('[data-upsell-add=sweet]');
  await page.select('[data-upsell-choice=tableware]', 'tableware:1:5');
  await page.click('[data-upsell-add=tableware]');
  const expected = [...bundles[0].items, { id: 'seabuckthorn', value: 1000, quantity: 1 }, { id: 'cherry', value: 500, quantity: 1 }, { id: 'tableware', value: 1, quantity: 5 }];
  assert.deepEqual(await selection(), expected);
  assert.equal(await page.$eval('[data-upsells]', el => el.hidden), true);
  assert.equal(await page.$eval('[data-total]', el => Number(el.textContent.replace(/\D/g, ''))), 2395);
  assert.equal(await page.$eval('[data-selection-grand-total]', el => Number(el.textContent.replace(/\D/g, ''))), 2895);
  await page.click('[data-order]');
  assert.equal(await page.$eval('#interest-dialog', dialog => dialog.open), true);
  assert.equal(await page.$$eval('[data-interest-items] li', rows => rows.length), 5);
  await page.screenshot({ path: `${screenshotDir}/form-${width}.png` });
  await page.reload({ waitUntil: 'networkidle0' });
  assert.deepEqual(await selection(), expected, 'additional choices persist on reload');
  await page.click('[data-open=selection-dialog]');
  await page.click('[data-item="cherry-500"] [data-remove]');
  assert.equal(await page.$eval('[data-upsell-group=sweet]', el => el.hidden), false, 'removing dessert restores its suggestion');
  await clear();
  await page.goto(`${origin}/menu/?qa=1#nabory`, { waitUntil: 'networkidle0' });
  assert.equal(await page.evaluate(() => document.body.scrollWidth <= innerWidth), true);
  assert.equal(await page.$$eval('[data-bundle]', buttons => buttons.every(button => button.getBoundingClientRect().height >= 48)), true);
  await page.$eval('#nabory', el => el.scrollIntoView());
  await page.screenshot({ path: `${screenshotDir}/menu-bundles-${width}.png` });
  await Promise.all([page.waitForNavigation({ waitUntil: 'networkidle0' }), page.click('[data-bundle=sweet-table]')]);
  assert.deepEqual(await selection(), bundles[2].items);
  await page.reload({ waitUntil: 'networkidle0' });
  assert.deepEqual(await selection(), bundles[2].items, 'bundle link does not add again on reload');
  await page.click('#selection-dialog [data-close]');
  await page.click('[data-bundle=sweet-table]');
  assert.deepEqual(await selection(), bundles[2].items.map(item => ({ ...item, quantity: 2 })), 'explicit repeat click adds one more complete set');
  console.log(`PASS: bundles, exact totals, contextual add-ons, five place settings, form handoff and reload at ${width}px`);
}
