import assert from 'node:assert/strict';
import { catalog } from '../../src/data/catalog.ts';
import { compositionLink } from '../../src/lib/selection-tools.ts';

export async function verifySelectionTools(page, origin, width, output) {
  const click = async selector => { await page.$eval(selector, el => el.scrollIntoView({ block: 'center', behavior: 'instant' })); await page.click(selector); };
  const selection = () => page.evaluate(() => JSON.parse(localStorage.getItem('pirogorsk-selection') || '[]'));
  const current = async items => { await page.evaluate(items => { localStorage.setItem('pirogorsk-selection', JSON.stringify(items)); window.dispatchEvent(new Event('focus')); }, items); };
  const field = async (selector, value) => page.$eval(selector, (el, value) => { el.value = String(value); el.dispatchEvent(new Event('input', { bubbles: true })); }, value);
  const amount = selector => page.$eval(selector, el => Number(el.textContent.replace(/\D/g, '')));
  const capture = async name => {
    await page.evaluate(() => Promise.all(document.getAnimations().filter(animation => animation.effect?.getTiming().iterations !== Infinity).map(animation => animation.finished.catch(() => {}))));
    await page.screenshot({ path: `${output}/${name}-${width}.png` });
  };
  await page.goto(`${origin}/podbor/?qa=1`, { waitUntil: 'networkidle0' });
  await field('[data-planner-form] [name=guests]', 7);
  const plannerLink = await page.$eval('[data-planner-continue]', el => el.href);
  assert.equal(new URL(plannerLink).searchParams.get('guests'), '7');
  const planned = new URL(plannerLink); planned.searchParams.set('qa', '1');
  await page.goto(planned.href, { waitUntil: 'networkidle0' });
  assert.equal(await page.$eval('[data-guest-form] [name=guests]', el => el.value), '7');
  assert.equal(await page.$eval('[data-guest-form] [name=settings]', el => el.value), '7');
  await page.goto(`${origin}/menu/?qa=1`, { waitUntil: 'networkidle0' });
  await page.evaluate(() => { localStorage.clear(); localStorage.setItem('pirogorsk-city', 'Калининград'); });
  await page.reload({ waitUntil: 'networkidle0' });
  await click('[data-edit-bundle="dinner"]');
  assert.equal(await page.$eval('#bundle-editor', el => el.open), true);
  assert.deepEqual(await selection(), [], 'editing a draft never adds products');
  await page.select('[data-bundle-row="0"] [data-bundle-field="id"]', 'fish');
  assert.equal(await page.$eval('[data-bundle-row="0"] [data-bundle-field="value"]', el => document.activeElement === el), true);
  await page.select('[data-bundle-row="0"] [data-bundle-field="value"]', '1000');
  await field('[data-bundle-row="0"] [data-bundle-field="quantity"]', 2);
  assert.equal(await amount('[data-bundle-total]'), 3570);
  assert.match(await page.$eval('[data-bundle-summary]', el => el.textContent), /10 порций.*2,5 кг/);
  await click('[data-bundle-row-add]');
  assert.equal(await page.$$eval('[data-bundle-row]', rows => rows.length), 3);
  await click('[data-bundle-row-remove="2"]');
  assert.equal(await page.$$eval('[data-bundle-row]', rows => rows.length), 2);
  await current([{ id: 'fish', value: 1000, quantity: 99 }]);
  await click('[data-bundle-form] button[type=submit]');
  assert.deepEqual(await selection(), [{ id: 'fish', value: 1000, quantity: 99 }], 'over-limit bundle rejects atomically');
  assert.match(await page.$eval('[data-bundle-status]', el => el.textContent), /не добавлен/);
  await current([]);
  await field('[data-bundle-row="0"] [data-bundle-field="quantity"]', 2);
  assert.equal(await page.$eval('#bundle-editor', el => el.scrollWidth <= el.clientWidth), true);
  await capture('bundle');
  await click('[data-bundle-form] button[type=submit]');
  const edited = [{ id: 'fish', value: 1000, quantity: 2 }, { id: 'cheese', value: 500, quantity: 1 }];
  assert.deepEqual(await selection(), edited);
  assert.equal(await amount('[data-total]'), 3570);
  assert.match(await page.$eval('[data-total-weight]', el => el.textContent), /10 порций.*2,5 кг/);
  await click('[data-favorite-save]');
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('pirogorsk-favorite')).items), edited);
  await click('[data-item="fish-1000"] [data-increase]');
  assert.equal((await selection())[0].quantity, 3);
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('pirogorsk-favorite')).items[0].quantity), 2, 'favorite is independent');
  await page.goto(`${origin}/delivery/?qa=1`, { waitUntil: 'networkidle0' });
  await click('.masthead-selection');
  await click('[data-favorite-open]');
  assert.equal(await page.$eval('#composition-preview', el => el.open), true);
  assert.equal((await selection())[0].quantity, 3, 'preview does not alter current');
  assert.equal(await amount('[data-preview-total]'), 3570);
  assert.match(await page.$eval('[data-preview-summary]', el => el.textContent), /10 порций.*2,5 кг/);
  await capture('favorite');
  await page.keyboard.press('Escape');
  assert.equal(await page.$eval('.masthead-selection', el => document.activeElement === el), true, 'nested dialog restores the original trigger');
  await click('.masthead-selection');
  await click('[data-favorite-open]');
  await click('[data-preview-apply=replace]');
  assert.deepEqual(await selection(), edited);
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { window.__sharedLink = text; } } }));
  await click('[data-share-selection]');
  const sharedLink = await page.evaluate(() => window.__sharedLink);
  assert.ok(new URL(sharedLink).hash.startsWith('#selection='));
  await current([{ id: 'apple', value: 500, quantity: 1 }]);
  const sharedPath = `${origin}/?qa=1${new URL(sharedLink).hash}`;
  await page.goto(sharedPath, { waitUntil: 'networkidle0' });
  assert.equal(await page.$eval('#composition-preview', el => el.open), true);
  assert.deepEqual(await selection(), [{ id: 'apple', value: 500, quantity: 1 }]);
  await click('[data-preview-apply=ensure]');
  const supplemented = await selection();
  assert.deepEqual(supplemented, [{ id: 'apple', value: 500, quantity: 1 }, ...edited]);
  assert.equal(new URL(page.url()).hash, '');
  await page.goto(sharedPath, { waitUntil: 'networkidle0' });
  await click('[data-preview-apply=ensure]');
  assert.deepEqual(await selection(), supplemented, 'reopening a link never duplicates quantities');
  assert.equal(await page.evaluate(() => localStorage.getItem('pirogorsk-city')), 'Калининград');
  await click('[data-favorite-delete]');
  assert.equal(await page.evaluate(() => localStorage.getItem('pirogorsk-favorite')), null);
  assert.deepEqual(await selection(), supplemented, 'deleting favorite preserves current');
  await click('[data-guest-tools] summary');
  await field('[data-guest-form] [name=guests]', 8);
  assert.equal(await page.$eval('[name=bottles]', el => el.value), '2');
  assert.equal(await page.$eval('[name=settings]', el => el.value), '8');
  await field('[name=bottles]', 1);
  await field('[name=settings]', 3);
  await click('[data-guest-add]');
  assert.ok((await selection()).some(item => item.id === 'cranberry' && item.value === 1000 && item.quantity === 1));
  assert.equal(await page.$eval('[name=bottles]', el => el.value), '1', 'already selected morse subtracted');
  assert.equal(await page.$eval('[name=settings]', el => el.value), '5');
  await page.select('[name=drink]', 'seabuckthorn:500');
  assert.equal(await page.$eval('[name=bottles]', el => el.value), '2', 'formats count volume across flavors');
  await click('[data-guest-add]');
  assert.equal(await page.$eval('[data-guest-add]', el => el.disabled), true);
  assert.match(await page.$eval('[data-guest-existing]', el => el.textContent), /2 л · посуда 8 наб/);
  assert.equal(await page.$eval('#selection-dialog', el => el.scrollWidth <= el.clientWidth), true);
  await capture('guests');
  const stale = compositionLink({ version: 1, city: 'Зеленоградск', items: [{ id: 'gone', value: 500, quantity: 1 }, edited[0]] }, origin);
  await page.goto(`${origin}/?qa=1${new URL(stale).hash}`, { waitUntil: 'networkidle0' });
  assert.match(await page.$eval('[data-preview-unavailable]', el => el.textContent), /1/);
  assert.equal(await amount('[data-preview-total]'), 2980);
  const allStale = compositionLink({ version: 1, city: 'Зеленоградск', items: [{ id: 'gone', value: 500, quantity: 1 }] }, origin);
  const beforeStale = await selection();
  await page.goto(`${origin}/?qa=1${new URL(allStale).hash}`, { waitUntil: 'networkidle0' });
  assert.equal(await page.$$eval('[data-preview-apply]', buttons => buttons.every(button => button.disabled)), true);
  assert.deepEqual(await selection(), beforeStale, 'an unavailable composition cannot replace current selection');
  const beforeInvalid = await selection();
  await page.goto(`${origin}/?qa=1#selection=%broken`, { waitUntil: 'networkidle0' });
  assert.match(await page.$eval('[data-tools-status]', el => el.textContent), /Не удалось прочитать/);
  assert.deepEqual(await selection(), beforeInvalid);
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('denied'); } } }));
  await click('[data-share-selection]');
  assert.equal(await page.$eval('[data-share-fallback]', el => !el.hidden && el.value.startsWith(location.origin)), true);
  // Denied storage must not claim successful favorite persistence or break this visit.
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('denied'); }; });
  await click('[data-favorite-save]');
  assert.match(await page.$eval('[data-tools-status]', el => el.textContent), /не разрешил/);
  assert.deepEqual(await selection(), beforeInvalid);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.equal(catalog.length, 153);
  console.log(`PASS: editable/atomic bundles, independent favorite, safe share preview/reapply/stale/fallback, guest top-ups and denied persistence at ${width}px`);
}
