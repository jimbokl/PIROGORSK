await fs.mkdir(dir,{recursive:true});
const manifest={};
for(const [slug,figures] of Object.entries(plans)){
 manifest[slug]=[];
 for(let i=0;i<figures.length;i++){
  const [heading,labels,caption]=figures[i];
  const cards=labels.map((label,j)=>{
   const x=40+j*390;const words=label.split('|');
   return `<rect x="${x}" y="160" width="340" height="310" rx="22" fill="${j===1?'#d8e4dd':'#e8ddc6'}"/><text x="${x+170}" y="230" text-anchor="middle" font-size="32" fill="#8b592f">0${j+1}</text>${words.map((w,k)=>`<text x="${x+170}" y="${words.length===1?345:325+k*65}" text-anchor="middle" font-size="${w.length>10?41:50}" fill="#274b43">${w}</text>`).join('')}`;
  }).join('');
  const svg=`<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="550" viewBox="0 0 1200 550"><rect width="1200" height="550" fill="#f4eee1"/><g font-family="Arial, sans-serif"><text x="40" y="90" font-size="43" fill="#274b43">${heading}</text>${cards}</g></svg>`;
  const name=slug+'-'+(i+1);
  await fs.writeFile(dir+'/'+name+'.svg',svg);
  await sharp(Buffer.from(svg)).png().toFile(dir+'/'+name+'.png');
  manifest[slug].push({afterSection:i===0?1:3,source:name+'.png',alt:heading+': '+labels.join(', ').replaceAll('|',' '),caption});
 }
}
await fs.writeFile('src/data/monthly-article-figures.json',JSON.stringify(manifest,null,2)+'\n');
