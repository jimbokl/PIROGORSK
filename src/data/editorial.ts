type ProductNoteKey = keyof typeof productNotes;
function noteKey(product: (typeof products)[number]): ProductNoteKey | undefined {
  const text = `${product.id} ${product.name}`.toLowerCase();
  if (/meat|мяс/.test(text)) return 'meat';
  if (/fish|рыб/.test(text)) return 'fish';
  if (/cabbage|капуст/.test(text)) return 'cabbage';
  if (/apple|яблок|брусник/.test(text)) return 'apple';
  if (/cherry|вишн/.test(text)) return 'cherry';
  if (/curd|cottage|raspberry|творог|малин/.test(text)) return 'curd';
  if (/cheese|сыр/.test(text)) return 'cheese';
  return undefined;
}

// One URL per recognised catalogue concept. Recipes, prices and availability stay out of this adapter.
const conceptImages = import.meta.glob<ImageMetadata>('../../design/layered-assets-v2/**/pie.png', { eager: true, import: 'default' });
const legacyImages = import.meta.glob<ImageMetadata>('../../design/assets-source/{meat,fish,cabbage,cheese}.png', { eager: true, import: 'default' });
export const editorialProducts = products.flatMap(product => {
  const key = noteKey(product);
  if (!key) return [];
  const entry = (manifest.pairs as Record<string, { status: string; files?: { pie?: { status?: string; path?: string } } }>)[product.visualKey ?? product.id];
  const file = entry?.files?.pie;
  const image = entry?.status === 'READY' && file?.status === 'READY' && file.path
    ? conceptImages[`../../design/layered-assets-v2/${file.path}`]
    : legacyImages[`../../design/assets-source/${product.id}.png`];
  return [{ ...product, image, editorial: { ...productNotes[key], slug: product.slug || productNotes[key].slug }, sweet: ['apple', 'cherry', 'curd'].includes(key) }];
});
export const productHref = (product: (typeof editorialProducts)[number]) => `/pirogi/${product.editorial.slug}/`;

